// scripts/inspect-revision-sessions.ts
// Read-only inspection tool — no INSERT, UPDATE, or DELETE is performed.
// Fetches all RevisionSessions (OPEN and COMPLETED), walks the full graph
// RevisionSession → Topic → RevisionSessionQuestion → Question → SessionLog
//                 → Mistake → DeepDiveNote
// and writes a structured JSON report to .local/reports/revision-session-inspection.json.
//
// Usage:
//   npm run inspect:revision-sessions
// or directly:
//   tsx scripts/inspect-revision-sessions.ts

import 'dotenv/config';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Pool } from 'pg';
import { PrismaPg } from '@prisma/adapter-pg';
import { PrismaClient } from '../generated/prisma/client.js';

// ---------------------------------------------------------------------------
// Bootstrap
// ---------------------------------------------------------------------------

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const repoRoot = resolve(__dirname, '..');

const OUTPUT_DIR = resolve(repoRoot, '.local', 'reports');
const OUTPUT_FILE = resolve(OUTPUT_DIR, 'revision-session-inspection.json');

if (!process.env['DATABASE_URL']) {
    console.error('ERROR: DATABASE_URL environment variable is not set.');
    console.error('       Load a .env file or set DATABASE_URL before running this script.');
    process.exit(1);
}

const pool = new Pool({ connectionString: process.env['DATABASE_URL'] });
const adapter = new PrismaPg(pool);
const prisma = new PrismaClient({ adapter });

// ---------------------------------------------------------------------------
// Types for the report shape
// ---------------------------------------------------------------------------

type QuestionRecord = {
    id: string;
    topicId: string;
    sessionType: string;
    format: string;
    prompt: string;
    options: unknown;
    correctAnswer: string | null;
    explanation: string | null;
    codeSnippet: string | null;
    createdAt: string;
};

type SessionLogRecord = {
    id: string;
    questionId: string;
    topicId: string;
    sessionId: string;
    sessionType: string;
    selectedAnswer: string;
    correct: boolean | null;
    confidence: string;
    answeredAt: string;
    autoGeneratedMistakeId: string | null;
};

type MistakeRecord = {
    id: string;
    topicId: string;
    questionId: string | null;
    sessionId: string | null;
    sourceSessionLogId: string | null;
    provenance: 'AUTO' | 'MANUAL';
    mistakeText: string;
    correctUnderstanding: string;
    turnedIntoQuestion: boolean;
    resolvedAt: string | null;
    createdAt: string;
};

type SessionQuestionRecord = {
    revisionSessionQuestionId: string;
    sortOrder: number;
    question: QuestionRecord;
    submittedAnswer: SessionLogRecord | null;
};

type DeepDiveNoteRecord = {
    id: string;
    topicId: string;
    reason: string;
    notes: string | null;
    createdAt: string;
    updatedAt: string;
};

type TopicRecord = {
    id: string;
    name: string;
    slug: string;
    area: string;
    category: string;
    status: string;
    intervalDays: number;
    nextRevisionDate: string;
    deepDiveNote: DeepDiveNoteRecord | null;
};

type SessionRecord = {
    id: string;
    status: string;
    startedAt: string;
    completedAt: string | null;
    outcome: string | null;
    policyVersion: string;
    previousIntervalDays: number | null;
    resultingIntervalDays: number | null;
    previousNextRevisionDate: string | null;
    resultingNextRevisionDate: string | null;
    topic: TopicRecord;
    assignedQuestions: SessionQuestionRecord[];
    sessionMistakes: MistakeRecord[];
    summary: {
        totalQuestions: number;
        answeredQuestions: number;
        correctAnswers: number | null;
        mistakes: number;
    };
};

type Report = {
    generatedAt: string;
    databaseUrl: string; // host only — no credentials
    totalSessions: number;
    openSessions: number;
    completedSessions: number;
    sessions: SessionRecord[];
};

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function maskDatabaseUrl(raw: string): string {
    try {
        const url = new URL(raw.replace(/^postgres(ql)?:/i, 'postgresql:'));
        return `${url.protocol}//<credentials-redacted>@${url.host}${url.pathname}`;
    } catch {
        return '<unable-to-parse-url>';
    }
}

function isoOrNull(d: Date | null | undefined): string | null {
    return d ? d.toISOString() : null;
}

// ---------------------------------------------------------------------------
// Main query and report builder
// ---------------------------------------------------------------------------

async function buildReport(): Promise<Report> {
    // Single query — fetch all sessions ordered newest first, with every
    // related record included. All reads; no mutations.
    const sessions = await prisma.revisionSession.findMany({
        orderBy: { startedAt: 'desc' },
        include: {
            topic: {
                include: {
                    deepDiveNote: true,
                },
            },
            questions: {
                orderBy: { sortOrder: 'asc' },
                include: {
                    question: true,
                },
            },
            logs: {
                include: {
                    mistakeFromSource: true,
                },
            },
            mistakes: true,
        },
    });

    const sessionRecords: SessionRecord[] = sessions.map((session) => {
        const { topic, questions, logs, mistakes } = session;

        // ---- Topic ----------------------------------------------------------
        const topicRecord: TopicRecord = {
            id: topic.id,
            name: topic.name,
            slug: topic.slug,
            area: topic.area,
            category: topic.category,
            status: topic.status,
            intervalDays: topic.intervalDays,
            nextRevisionDate: topic.nextRevisionDate.toISOString(),
            deepDiveNote: topic.deepDiveNote
                ? {
                      id: topic.deepDiveNote.id,
                      topicId: topic.deepDiveNote.topicId,
                      reason: topic.deepDiveNote.reason,
                      notes: topic.deepDiveNote.notes ?? null,
                      createdAt: topic.deepDiveNote.createdAt.toISOString(),
                      updatedAt: topic.deepDiveNote.updatedAt.toISOString(),
                  }
                : null,
        };

        // ---- Build a lookup: questionId → SessionLog for this session --------
        const logByQuestionId = new Map(logs.map((log) => [log.questionId, log]));

        // ---- Assigned questions with their submitted answers -----------------
        const assignedQuestions: SessionQuestionRecord[] = questions.map((rsq) => {
            const q = rsq.question;
            const questionRecord: QuestionRecord = {
                id: q.id,
                topicId: q.topicId,
                sessionType: q.sessionType,
                format: q.format,
                prompt: q.prompt,
                options: q.options,
                correctAnswer: q.correctAnswer ?? null,
                explanation: q.explanation ?? null,
                codeSnippet: q.codeSnippet ?? null,
                createdAt: q.createdAt.toISOString(),
            };

            const log = logByQuestionId.get(q.id);
            const submittedAnswer: SessionLogRecord | null = log
                ? {
                      id: log.id,
                      questionId: log.questionId,
                      topicId: log.topicId,
                      sessionId: log.sessionId,
                      sessionType: log.sessionType,
                      selectedAnswer: log.selectedAnswer,
                      correct: log.correct ?? null,
                      confidence: log.confidence,
                      answeredAt: log.answeredAt.toISOString(),
                      autoGeneratedMistakeId: log.mistakeFromSource?.id ?? null,
                  }
                : null;

            return {
                revisionSessionQuestionId: rsq.id,
                sortOrder: rsq.sortOrder,
                question: questionRecord,
                submittedAnswer,
            };
        });

        // ---- Session-level mistakes ------------------------------------------
        const sessionMistakes: MistakeRecord[] = mistakes.map((m) => ({
            id: m.id,
            topicId: m.topicId,
            questionId: m.questionId ?? null,
            sessionId: m.sessionId ?? null,
            sourceSessionLogId: m.sourceSessionLogId ?? null,
            provenance: m.sourceSessionLogId ? 'AUTO' : 'MANUAL',
            mistakeText: m.mistakeText,
            correctUnderstanding: m.correctUnderstanding,
            turnedIntoQuestion: m.turnedIntoQuestion,
            resolvedAt: isoOrNull(m.resolvedAt),
            createdAt: m.createdAt.toISOString(),
        }));

        // ---- Summary counts --------------------------------------------------
        const answeredCount = logs.length;
        const correctCount = logs.filter((l) => l.correct === true).length;
        // If no log has a non-null correct field, report null to avoid misleading 0
        const anyGraded = logs.some((l) => l.correct !== null);

        return {
            id: session.id,
            status: session.status,
            startedAt: session.startedAt.toISOString(),
            completedAt: isoOrNull(session.completedAt),
            outcome: session.outcome ?? null,
            policyVersion: session.policyVersion,
            previousIntervalDays: session.previousIntervalDays ?? null,
            resultingIntervalDays: session.resultingIntervalDays ?? null,
            previousNextRevisionDate: isoOrNull(session.previousNextRevisionDate),
            resultingNextRevisionDate: isoOrNull(session.resultingNextRevisionDate),
            topic: topicRecord,
            assignedQuestions,
            sessionMistakes,
            summary: {
                totalQuestions: questions.length,
                answeredQuestions: answeredCount,
                correctAnswers: anyGraded ? correctCount : null,
                mistakes: mistakes.length,
            },
        };
    });

    const openCount = sessionRecords.filter((s) => s.status === 'OPEN').length;
    const completedCount = sessionRecords.filter((s) => s.status === 'COMPLETED').length;

    return {
        generatedAt: new Date().toISOString(),
        databaseUrl: maskDatabaseUrl(process.env['DATABASE_URL']!),
        totalSessions: sessionRecords.length,
        openSessions: openCount,
        completedSessions: completedCount,
        sessions: sessionRecords,
    };
}

// ---------------------------------------------------------------------------
// Entry point
// ---------------------------------------------------------------------------

async function main(): Promise<void> {
    console.log('inspect-revision-sessions: connecting to database…');

    let report: Report;
    try {
        report = await buildReport();
    } finally {
        await prisma.$disconnect();
        await pool.end();
    }

    console.log(
        `inspect-revision-sessions: fetched ${report.totalSessions} session(s) ` +
            `(${report.openSessions} OPEN, ${report.completedSessions} COMPLETED).`,
    );

    // Write report — create output directory if it doesn't exist.
    mkdirSync(OUTPUT_DIR, { recursive: true });
    writeFileSync(OUTPUT_FILE, JSON.stringify(report, null, 2), 'utf-8');

    console.log(`inspect-revision-sessions: report written to ${OUTPUT_FILE}`);
}

main().catch((err: unknown) => {
    console.error('inspect-revision-sessions: fatal error:', err);
    process.exitCode = 1;
});
